/** Anchors that prove a route has actually finished rendering. */
export async function waitForRoute(page: Page, name: RouteName) {
  switch (name) {
    case 'watch':
      await expect(page.getByTestId('scenario-list')).toBeVisible()
      break
    case 'scene':
      await expect(page.locator('.analysis-layout, [role="alert"], [role="status"]').first()).toBeVisible()
      break
    case 'attribution':
      await expect(page.locator('.attribution-layout, [role="alert"], [role="status"]').first()).toBeVisible()
      break
    case 'dossier':
      await expect(page.locator('.record-page, [role="alert"], [role="status"]').first()).toBeVisible()
      break
    case 'calibration':
      await expect(page.locator('.record-page, [role="alert"], [role="status"]').first()).toBeVisible()
      break
    case 'about':
      await expect(page.getByRole('heading', { name: 'Method', exact: true })).toBeVisible()
      break
    case 'notFound':
      await expect(page.getByRole('heading', { name: 'No such page' })).toBeVisible()
      break
  }
}

/** Anchors that prove a route has rendered its actual data, not a placeholder.
 *  Used wherever a measurement (contrast, geometry) has to be taken against
 *  real content rather than a skeleton. */
export async function waitForContent(page: Page, name: RouteName) {
  switch (name) {
    case 'watch':
      await expect(page.getByTestId('alert-row').first()).toBeVisible()
      await expect(page.getByTestId('run-scenario-elsa3')).toBeVisible()
      break
    case 'scene':
      await expect(page.getByTestId('wind-gate')).toBeVisible()
      await expect(page.getByTestId('lookalike-panel')).toBeVisible()
      break
    case 'attribution':
      await expect(page.getByTestId('h0-row')).toBeVisible()
      await expect(page.getByTestId('candidate-row').first()).toBeVisible()
      await expect(page.getByTestId('timeline')).toBeVisible()
      break
    case 'dossier':
      await expect(page.getByTestId('download-pdf')).toBeVisible()
      await expect(page.getByRole('heading', { name: 'Vessel' })).toBeVisible()
      break
    case 'calibration':
      await expect(page.getByTestId('reliability-diagram')).toBeVisible()
      break
    case 'about':
      await expect(page.getByRole('heading', { name: 'Method', exact: true })).toBeVisible()
      await expect(page.getByRole('heading', { name: 'Runtime capability' })).toBeVisible()
      break
    case 'notFound':
      await expect(page.getByRole('heading', { name: 'No such page' })).toBeVisible()
      break
  }
}

/** Navigate and wait until the route's content is on screen and settled. */
export async function goto(page: Page, name: RouteName) {
  await page.goto(ROUTES[name])
  await waitForRoute(page, name)
  await settle(page)
}

/** Navigate and wait until the route's real data has rendered and settled. */
export async function gotoReady(page: Page, name: RouteName) {
  await page.goto(ROUTES[name])
  await waitForContent(page, name)
  await settle(page)
}

/** Wait until every finite animation has finished.
 *
 *  Entry animations fade text in from zero opacity. Measuring colour contrast
 *  or geometry part-way through one reads a value that exists for a few frames
 *  and depends entirely on when the frame was sampled. Waiting for the
 *  animations to finish is what makes those measurements mean something. */
export async function settle(page: Page) {
  await page.waitForFunction(
    () =>
      document
        .getAnimations()
        .filter((animation) => {
          const timing = animation.effect?.getComputedTiming()
          return timing !== undefined && timing.iterations !== Infinity
        })
        .every((animation) => animation.playState === 'finished' || animation.playState === 'idle'),
    undefined,
    { timeout: 10_000 },
  )
}

const JUNK = ['undefined', 'NaN', '[object Object]'] as const

/** No placeholder ever reaches the analyst's screen. */
export async function expectNoRenderedJunk(page: Page, where: string) {
  const text = await page.evaluate(() => document.body.innerText)
  for (const needle of JUNK) {
    expect(
      text.includes(needle),
      `${where}: rendered text must not contain the literal "${needle}".\n` +
        `Offending excerpt: ${excerpt(text, needle)}`,
    ).toBe(false)
  }
}

function excerpt(text: string, needle: string): string {
  const at = text.indexOf(needle)
  if (at < 0) return '(none)'
  return JSON.stringify(text.slice(Math.max(0, at - 90), at + needle.length + 90))
}

/** The interface renders a true minus sign (U+2212) for negatives. */
export function parseSignedNumber(text: string): number {
  const normalised = text.trim().replace(/\u2212/g, '-').replace(/^\+/, '')
  const value = Number(normalised)
  expect(Number.isFinite(value), `expected a number, got ${JSON.stringify(text)}`).toBe(true)
  return value
}
