export interface Reply {
  status?: number
  json?: unknown
  body?: string
  contentType?: string
}

export type Handler = Reply | ((context: { url: URL; method: string; key: StubKey }) => Reply | Promise<Reply>)

/** Map a request onto one of the stub keys, or null when it is not an API call. */
export function classify(url: URL, method: string): StubKey | null {
  const p = url.pathname
  if (!p.startsWith('/api/v1/')) return null
  if (p === '/api/v1/health') return 'health'
  if (p === '/api/v1/scenarios') return 'scenarios'
  if (p === '/api/v1/scenes') return 'scenes'
  if (p === '/api/v1/scenes/ingest' && method === 'POST') return 'ingest'
  if (p.endsWith('/raster.png')) return 'raster'
  if (/^\/api\/v1\/scenes\/[^/]+\/detections$/.test(p)) return 'detections'
  if (/^\/api\/v1\/scenes\/[^/]+$/.test(p)) return 'scene'
  if (p === '/api/v1/candidates/generate') return 'candidatesGenerate'
  if (p === '/api/v1/candidates') return 'candidates'
  if (p === '/api/v1/attribution/run') return 'attributionRun'
  if (/^\/api\/v1\/attribution\/[^/]+\/sim\/.+$/.test(p)) return 'simulation'
  if (/^\/api\/v1\/attribution\/[^/]+$/.test(p)) return 'attribution'
  if (/^\/api\/v1\/jobs\/[^/]+$/.test(p)) return 'job'
  if (p.startsWith('/api/v1/dossier')) return 'dossier'
  if (p === '/api/v1/handoff/oosa') return 'handoff'
  if (p === '/api/v1/calibration') return 'calibration'
  return null
}

const DEFAULTS: Record<StubKey, () => Reply> = {
  health: () => ({ json: health() }),
  scenarios: () => ({ json: scenarios() }),
  scenes: () => ({ json: scenes() }),
  scene: () => ({ json: scene() }),
  detections: () => ({ json: detections() }),
  // The SAR raster is a basemap underlay. Nothing in the suite reads its
  // pixels, and the app is written to degrade when it cannot be fetched, so
  // it is refused rather than faked with a binary body.
  raster: () => ({ status: 404, json: { detail: 'Raster imagery is not served in the test harness.' } }),
  ingest: () => ({ json: { job_id: 'job-ingest' } }),
  candidatesGenerate: () => ({ json: { job_id: 'job-candidates' } }),
  candidates: () => ({ json: candidates() }),
  attributionRun: () => ({ json: { job_id: 'job-attribution' } }),
  attribution: () => ({ json: attribution() }),
  simulation: () => ({ json: simulation() }),
  job: () => ({ json: jobs.ingest() }),
  dossier: () => ({ json: dossier() }),
  handoff: () => ({ json: handoff() }),
  calibration: () => ({ json: calibration() }),
}

async function fulfil(route: Route, reply: Reply) {
  const headers: Record<string, string> = {
    'access-control-allow-origin': '*',
    'access-control-allow-headers': '*',
    'access-control-allow-methods': 'GET,POST,OPTIONS',
    'cache-control': 'no-store',
  }
  if (reply.json !== undefined) {
    await route.fulfill({
      status: reply.status ?? 200,
      contentType: 'application/json',
      headers,
      body: JSON.stringify(reply.json),
    })
    return
  }
  await route.fulfill({
    status: reply.status ?? 200,
    contentType: reply.contentType ?? 'text/plain',
    headers,
    body: reply.body ?? '',
  })
}

/** Install the API stub. Overrides replace a single endpoint's behaviour. */
export async function stubApi(page: Page, overrides: Partial<Record<StubKey, Handler>> = {}) {
  await page.route('**/api/v1/**', async (route) => {
    const request = route.request()
    const method = request.method()
    const url = new URL(request.url())
    if (method === 'OPTIONS') {
      await fulfil(route, { status: 204, body: '' })
      return
    }
    const key = classify(url, method)
    if (key === null) {
      await fulfil(route, { status: 404, json: { detail: `No stub for ${method} ${url.pathname}` } })
      return
    }
    const override = overrides[key]
    const reply =
      override === undefined
        ? DEFAULTS[key]()
        : typeof override === 'function'
          ? await override({ url, method, key })
          : override
    await fulfil(route, reply)
  })
}

/** Jobs are polled by followJob(); dispatch on the job id the app was given. */
export const jobRouter: Handler = ({ url }) => {
  const id = url.pathname.split('/').pop() ?? ''
  if (id.includes('candidates')) return { json: jobs.candidates() }
  if (id.includes('attribution')) return { json: jobs.attribution() }
  return { json: jobs.ingest() }
}

