/* Evidence terms are constructed so that, for every candidate:
 *    sum(likelihood terms) === log_likelihood
 *    sum(prior terms)      === log_prior
 *    sum(all terms)        === score
 * which is exactly the invariant core/score/attribute.py asserts. */
const evidenceFor = (
  likelihood: [string, number, string][],
  prior: [string, number, string][],
) => {
  const terms = [
    ...likelihood.map(([name, value, explanation]) => ({ group: 'likelihood' as const, name, value, explanation })),
    ...prior.map(([name, value, explanation]) => ({ group: 'prior' as const, name, value, explanation })),
  ]
  const round6 = (n: number) => Number(n.toFixed(6))
  const logL = round6(likelihood.reduce((a, [, v]) => a + v, 0))
  const logPi = round6(prior.reduce((a, [, v]) => a + v, 0))
  return {
    terms,
    sum: round6(logL + logPi),
    score: round6(logL + logPi),
    log_likelihood: logL,
    log_prior: logPi,
  }
}

